/**
 * Единый формат «сырого» поста для всех типов источников. Парсеры (Telegram,
 * сайты) возвращают `RawPost[]` — pipeline дальше превращает в monitoring_items.
 */

/**
 * Метрики вовлечённости поста (просмотры/реакции/комментарии). У разных
 * источников доступны разные поля — все опциональны.
 *
 * - Telegram (`t.me/s/`) отдаёт `views` (как число вида "1.2K"), массив
 *   реакций с эмодзи и счётчиком, а также `forwards` для «горячих» постов.
 *   Комментарии (`comments`) — это просто число ответов в обсуждении, если
 *   у канала включён linked-chat.
 * - Сайты через RSS иногда отдают `slash:comments` (количество комментов на
 *   странице). Views и реакций в стандартном RSS нет.
 */
export interface PostEngagement {
  /** Количество просмотров. */
  views?: number
  /** Сумма всех реакций. */
  reactionsTotal?: number
  /** Реакции по эмодзи (для подсказок «топ-эмодзи»). */
  reactions?: Array<{ emoji: string; count: number }>
  /** Количество комментариев / ответов. */
  comments?: number
  /** Количество репостов (для TG-каналов с включёнными статистиками). */
  forwards?: number
}

export interface RawPost {
  /** Стабильный id поста внутри источника — для дедупа между запусками. */
  sourcePostId: string
  /** Прямая ссылка на пост / статью. */
  postUrl: string
  /** Время публикации. Null допустим — если источник не отдал. */
  publishedAt?: Date
  /** Заголовок (для статей) или первая строка (для постов TG). */
  title?: string
  /** Полный текст. Plain или markdown. */
  content: string
  /** Прикреплённые изображения. */
  images: Array<{ url: string; width?: number; height?: number }>
  /** Метрики вовлечённости — пустой объект если ничего не нашлось. */
  engagement?: PostEngagement
}
